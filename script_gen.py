def _round_robin():
    """分類ラウンドロビン（朝→移動→本番前→人間関係→夜）順の予備プール。"""
    by_cat = {c: [s for s in _STOCK if s[0] == c] for c in CATEGORIES}
    pool, i = [], 0
    while any(i < len(v) for v in by_cat.values()):
        for c in CATEGORIES:
            if i < len(by_cat[c]):
                cat, c1, c2, note = by_cat[c][i]
                pool.append({"category": cat, "card1": c1, "card2": c2,
                             "note": note, "comment_lead": _FALLBACK_COMMENT,
                             "new_rule": ""})
        i += 1
    return pool


